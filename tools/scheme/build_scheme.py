def cor(routes: str, *pts, r: float | None = None, fit: bool = True) -> None:
    """Коридор: маршруты слева направо по ходу движения вдоль pts; r — радиус скругления углов."""
    CORRIDORS.append({"routes": routes.split(), "pts": [list(p) for p in pts], **({"r": r} if r else {}), **({} if fit else {"nofit": 1})})


def st(name: str, x: float, y: float, side: str = "r", *, bold: bool = False, metro: bool = False, rot: int = 0, at: tuple | None = None) -> None:
    """Остановка: side — где подпись (l, r, t, b, tl, tr, bl, br); rot — поворот подписи (−45 для диагональных)."""
    s = {"n": name, "p": [x, y], "a": side}
    if bold:
        s["b"] = 1
    if metro:
        s["m"] = 1
    if rot:
        s["rot"] = rot
    if at:
        s["lp"] = list(at)  # подпись отдельно от точки (где у точки нет места)
    STOPS.append(s)


def term(routes: str, x: float, y: float) -> None:
    """Плашки номеров маршрутов у конечной (левый верхний угол ряда плашек)."""
    TERMS.append({"routes": routes.split(), "p": [x, y]})


