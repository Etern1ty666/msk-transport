def check() -> None:
    bad = 0
    for c in CORRIDORS:
        for (x1, y1), (x2, y2) in zip(c["pts"], c["pts"][1:]):
            a = math.degrees(math.atan2(y2 - y1, x2 - x1)) % 45
            dev = min(a, 45 - a)
            if dev > 2.5:
                bad += 1
                print(f"  ! не октилинейно ({dev:.1f}°): {c['routes']} {(x1, y1)} → {(x2, y2)}")
    unknown = {r for c in CORRIDORS for r in c["routes"]} - set(ROUTES)
    if unknown:
        print("  ! неизвестные маршруты:", unknown)
    print(f"коридоров {len(CORRIDORS)}, остановок {len(STOPS)}, конечных {len(TERMS)}, предупреждений {bad}")


